#!/usr/bin/env python3
"""H-subtail probe: does the PURE-48th jitter rate ({1,5,7,11} mod 12 — the cells grid_snap vetoes, which humans
never use) rise toward the END of the song, and does harm_calib (esp. PERC) CONCENTRATE it into that tail?

Observational — reads the already-generated Bye Bye arms (no new generation). Two questions:
  (a) BASE defect: is jitter monotone-increasing with normalized song position across ALL arms?
  (b) RELOCATION: does HARM-PERC's tail jitter exceed GLOBAL/OFF (density-preserving budget dumped into the
      perc-absent, PE-extrapolated, grid_snap-OFF-at-Hard tail)?
"""
import warnings, os, sys
warnings.filterwarnings('ignore'); os.environ['AUDIOREAD_LOG_LEVEL'] = 'ERROR'
from pathlib import Path
import numpy as np
ROOT = Path('/home/ybx/code/stepmania-chart-generator'); sys.path.insert(0, str(ROOT))
from src.data.stepmania_parser import StepManiaParser

PROBE = Path('/home/ybx/sm-generated/stamina_probe')
SUBDIV = 12
JITTER = {1, 5, 7, 11}            # pure-48th cells grid_snap vetoes
TRIPLET = {2, 4, 8, 10}          # kept by grid_snap_keep_triplets
ONGRID_DUPLE = {0, 3, 6, 9}      # quarter / 16th-duple / 8th
ARMS = ['OFF', 'GLOBAL', 'LOCAL', 'HARM-TOTAL', 'HARM-PERC']
NBINS = 10


def present_frames(arm):
    sm = PROBE / f"Bye Bye {arm}" / "chart.sm"
    if not sm.is_file():
        return None
    P = StepManiaParser.for_v2(subdiv=SUBDIV, min_song_length=30.0, max_song_length=600.0,
                               min_bpm=40.0, max_bpm=320.0, max_simultaneous=4, gimmick_max_bpm=400.0)
    c = P.parse_file(str(sm))
    nd = next((n for n in c.note_data if n.difficulty_name), None)
    t = np.asarray(P.convert_to_tensor_typed(c, nd))
    pres = ((t == 1) | (t == 2) | (t == 4)).any(1)     # tap/hold-head/roll-head = a note present
    return pres


def main():
    print(f"H-subtail | pure-48th jitter phases {sorted(JITTER)} (mod {SUBDIV}) | {NBINS} position bins\n")
    header = "arm         Nnotes  jit%   trip% |" + "".join(f" b{i}" for i in range(NBINS)) + " | tail/body"
    print(header); print("-" * len(header))
    for arm in ARMS:
        pres = present_frames(arm)
        if pres is None:
            print(f"{arm:11s} (missing)"); continue
        idx = np.nonzero(pres)[0]
        T = len(pres)
        phase = idx % SUBDIV
        is_jit = np.isin(phase, list(JITTER))
        is_trip = np.isin(phase, list(TRIPLET))
        pos = idx / max(T - 1, 1)                        # normalized 0..1
        bins = np.clip((pos * NBINS).astype(int), 0, NBINS - 1)
        # per-bin jitter RATE = jitter notes / all notes in that positional bin
        rates = []
        for b in range(NBINS):
            m = bins == b
            rates.append(is_jit[m].mean() if m.any() else np.nan)
        rates = np.array(rates)
        # tail (last 20% = bins 8,9) vs body (bins 0..7)
        tail = np.nanmean(rates[8:]); body = np.nanmean(rates[:8])
        ratio = tail / body if body > 1e-9 else np.inf
        bstr = "".join(f"{r*100:3.0f}" if not np.isnan(r) else "  ." for r in rates)
        bstr = " ".join(f"{r*100:2.0f}" if not np.isnan(r) else " ." for r in rates)
        print(f"{arm:11s} {len(idx):6d} {is_jit.mean()*100:5.1f} {is_trip.mean()*100:5.1f} | {bstr} | {ratio:5.2f}x")

    print("\n(b0..b9 = jitter% within each 10% slice of the song; last two = the tail. tail/body>1 => tail-concentrated.)")
    print("Read (a) is jitter monotone-rising L->R within a row? (b) is HARM-PERC's tail worse than OFF/GLOBAL?")

    # LENGTH CONFOUND: is the tail-jitter cliff WORSE on longer songs (PE-extrapolation)? GLOBAL arm, 3 songs.
    print("\n--- length confound (GLOBAL arm across the 3 songs, ranked by length) ---")
    print(f"{'song':10s} {'Tframes':>8s} {'jit%':>6s} {'b8%':>6s} {'b9(tail)%':>10s}")
    P = StepManiaParser.for_v2(subdiv=SUBDIV, min_song_length=30.0, max_song_length=600.0,
                               min_bpm=40.0, max_bpm=320.0, max_simultaneous=4, gimmick_max_bpm=400.0)
    for song in ['Calling', 'Switch', 'Bye Bye']:
        sm = PROBE / f"{song} GLOBAL" / "chart.sm"
        if not sm.is_file():
            print(f"{song:10s} (missing)"); continue
        c = P.parse_file(str(sm)); nd = next((n for n in c.note_data if n.difficulty_name), None)
        t = np.asarray(P.convert_to_tensor_typed(c, nd))
        pres = ((t == 1) | (t == 2) | (t == 4)).any(1)
        idx = np.nonzero(pres)[0]; T = len(pres)
        is_jit = np.isin(idx % SUBDIV, list(JITTER))
        bins = np.clip(((idx / max(T - 1, 1)) * NBINS).astype(int), 0, NBINS - 1)
        b8 = is_jit[bins == 8].mean() if (bins == 8).any() else np.nan
        b9 = is_jit[bins == 9].mean() if (bins == 9).any() else np.nan
        print(f"{song:10s} {T:8d} {is_jit.mean()*100:6.1f} {b8*100:6.1f} {b9*100:10.1f}")
    print("(if b9 rises with Tframes => the tail cliff is a LENGTH/PE-extrapolation effect, not a harm_calib one.)")

    # SMEAR (backbone dissolving) — the user's correction: it's not just jitter cells, the WHOLE phase distribution
    # flattens in the tail. Metric = Herfindahl concentration of the 12-phase histogram (high=peaked backbone,
    # low=uniform smear) + quarter/8th backbone share. Compare TAIL (last 20%) vs BODY (first 80%), per arm.
    print("\n--- SMEAR: tail (last 20%) phase-distribution vs body, per Bye Bye arm ---")
    print(f"{'arm':11s} | {'region':6s} {'notes':>5s} {'quarter%':>8s} {'8th%':>5s} {'16dup%':>6s} "
          f"{'trip%':>5s} {'jit%':>5s} {'concentr(H)':>11s}")
    print("-" * 78)
    for arm in ARMS:
        pres = present_frames(arm)
        if pres is None:
            continue
        idx = np.nonzero(pres)[0]; T = len(pres)
        pos = idx / max(T - 1, 1)
        for label, mask in [('body', pos < 0.8), ('TAIL', pos >= 0.8)]:
            ph = idx[mask] % SUBDIV
            n = len(ph)
            if n == 0:
                print(f"{arm:11s} | {label:6s} {n:>5d}  (empty)"); continue
            hist = np.array([(ph == k).sum() for k in range(SUBDIV)], dtype=np.float64)
            p = hist / n
            H = (p ** 2).sum()                       # Herfindahl: 1=all one phase, 1/12=uniform smear
            q = p[0]; e8 = p[6]
            dup16 = p[3] + p[9]
            trip = sum(p[k] for k in TRIPLET)
            jit = sum(p[k] for k in JITTER)
            print(f"{arm:11s} | {label:6s} {n:>5d} {q*100:>8.0f} {e8*100:>5.0f} {dup16*100:>6.0f} "
                  f"{trip*100:>5.0f} {jit*100:>5.0f} {H:>11.3f}")
    print("(H=Herfindahl phase concentration; uniform-smear floor=1/12≈0.083. Lower H in TAIL => backbone dissolving.")
    print(" Compare HARM-PERC TAIL H vs GLOBAL/OFF TAIL H: lower => harm_calib worsened the smear, not just jitter.)")

    # DENSITY by position — does harm_calib RELOCATE density into the degrading final bins (b8,b9)? notes/frame per bin.
    print("\n--- DENSITY by position (notes per frame x1000), per Bye Bye arm ---")
    print(f"{'arm':11s} |" + "".join(f" b{i:<2d}" for i in range(NBINS)) + " | b9/body")
    print("-" * 74)
    for arm in ARMS:
        pres = present_frames(arm)
        if pres is None:
            continue
        T = len(pres); idx = np.nonzero(pres)[0]
        bins_all = np.clip((np.arange(T) / max(T - 1, 1) * NBINS).astype(int), 0, NBINS - 1)
        note_bins = np.clip((idx / max(T - 1, 1) * NBINS).astype(int), 0, NBINS - 1)
        dens = np.array([(note_bins == b).sum() / max((bins_all == b).sum(), 1) for b in range(NBINS)])
        body = dens[:8].mean()
        dstr = "".join(f"{d*1000:4.0f}" for d in dens)
        print(f"{arm:11s} |{dstr} | {dens[9]/max(body,1e-9):5.2f}x")
    print("(if HARM-PERC's b8/b9 density exceeds GLOBAL's => it relocates budget INTO the degrading tail = the felt 'worse'.)")


if __name__ == '__main__':
    main()
